const messages: Record<Language, Record<keyof typeof english, string>> = {
  en: english,
  tr: turkish,
};

export type TranslationKey = keyof typeof english;

export function translate(
  language: Language,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  const message: string = messages[language][key];
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(values[name] ?? placeholder),
  );
}

export function detectPreferredLanguage(): Language {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("tr")
    ? "tr"
    : "en";
}
